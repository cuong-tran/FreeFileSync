bool zen::isCrashReportingAvailable() { return true; }


void zen::initCrashReporting(const CrashReportConfig& cfg) //throw SysError
{
    if (!cfg.enabled)
        return;
    if (globalActive)
        throw SysError(L"Crash reporting is already initialized.");
    if (cfg.dsn.empty())
        throw SysError(L"No DSN.");

    try
    {
        if (!itemExists(cfg.handlerPath)) //throw FileError
            throw SysError(L"Crash handler not found: " + utfTo<std::wstring>(cfg.handlerPath));

        createDirectoryIfMissingRecursion(cfg.databasePath); //throw FileError
    }
    catch (const FileError& e) { throw SysError(e.toString()); }

    globalPrivateWords = cfg.privateWords;
    globalDatabasePath = cfg.databasePath;

    sentry_options_t* opts = sentry_options_new();
    if (!opts)
        throw SysError(L"sentry_options_new failed.");

    sentry_options_set_dsn(opts, cfg.dsn.c_str());
    sentry_options_set_release(opts, cfg.release.c_str());
    sentry_options_set_environment(opts, cfg.environment.c_str());
    sentry_options_set_database_path(opts, toSentryPath(cfg.databasePath).c_str());
    sentry_options_set_handler_path(opts, toSentryPath(cfg.handlerPath).c_str());
    if (!cfg.caCertPath.empty())
        sentry_options_set_ca_certs(opts, toSentryPath(cfg.caCertPath).c_str());

    //privacy defaults: no PII, nothing but crashes and internal errors, no extra attachments
    //(send_default_pii: off by default; its setter exists only in sentry-native's Nintendo Switch build)
    sentry_options_set_send_client_reports(opts, 0); //no statistics about dropped events either
    /*  Consent: sentry-native stores it in <database>/user-consent, shared by all processes (FreeFileSync GUI, batch runs, ...),
        and applies it in sentry_init(). The apps then set it from the user's setting, so the file only ever holds what the
        user answered (or "unknown" before the first-start notice). Without consent, http_retry keeps envelopes in
        <database>/cache instead of discarding them (sentry__submit_envelope() in 0.17.6), and Crashpad's uploads are paused
        rather than disabled, which keeps crash reports pending: both are sent once the consent is given, also those of
        earlier runs (sentry__process_old_runs() resubmits them), and deleted by setCrashReportingConsent(revoked).
        Sharing the database is supported: each process has its own locked "<id>.run" folder, and Crashpad's database
        locks each report and its settings file.                                                                           */
    sentry_options_set_require_user_consent(opts, 1);
#if defined ZEN_MAC
    /*  sentry-native pauses Crashpad's uploads (keeping reports pending) instead of disabling them whenever http_retry is on, also
        for a revoked consent: started with the stored answer "don't send", leave it off, so that Crashpad's uploads are disabled
        (see markRevokedPeriod(): the reports are deleted anyway). The file holds "0" for a revoked consent. */
    bool storedRevoked = false;
    try { storedRevoked = getFileContent(appendPath(cfg.databasePath, Zstr("user-consent")), nullptr).starts_with('0'); } //throw FileError
    catch (FileError&) {} //no file: no answer stored
    sentry_options_set_http_retry(opts, storedRevoked ? 0 : 1);
#else
    sentry_options_set_http_retry(opts, 1); //also retries uploads that failed for network reasons
#endif
    sentry_options_set_auto_session_tracking(opts, 0); //no release health sessions: they are neither crashes nor errors
    sentry_options_set_max_breadcrumbs(opts, 50);
    sentry_options_set_attach_stacktrace(opts, 1); //group internal errors by call site
    sentry_options_set_shutdown_timeout(opts, 2000 /*ms*/);
    sentry_options_set_before_send(opts, beforeSend, nullptr);
    sentry_options_set_on_crash(opts, onCrash, nullptr);
    sentry_options_set_debug(opts, ::getenv("FFS_CRASH_REPORT_DEBUG") ? 1 : 0);

    //sentry_init() takes ownership of opts, even on failure
    if (const int rv = sentry_init(opts);
        rv != 0)
        throw SysError(L"sentry_init failed with code " + numberTo<std::wstring>(rv) + L'.');

    //sentry-native gives events a user object with a random installation ID by default: send none at all
    sentry_set_user(sentry_value_new_null());
    sentry_set_tag("app", cfg.appName.c_str());

    //until the app applies its setting, the consent stored by the last process holds: "don't send" must already apply to
    //a crash now (onCrash())
    if (sentry_user_consent_get() == SENTRY_USER_CONSENT_REVOKED)
    {
        globalConsent = CrashReportConsent::revoked;
#if defined ZEN_MAC //a crash now leaves a dump (see markRevokedPeriod())
        markRevokedPeriod(cfg.databasePath);
#endif
    }

    globalActive = true;

    static bool quickExitRegistered = false;
    if (!quickExitRegistered)
    {
        startFlushHelper();
        quickExitRegistered = std::at_quick_exit(onQuickExit) == 0;
    }
}


bool zen::isCrashReportingActive() { return globalActive; }


void zen::setCrashReportingConsent(CrashReportConsent consent)
{
    if (!globalActive)
        return;
    globalConsent = consent;
    globalWithholdOwn = consent == CrashReportConsent::unknown && sentry_user_consent_get() == SENTRY_USER_CONSENT_GIVEN;
    switch (consent)
    {
        case CrashReportConsent::unknown:
            //no answer of our own: leave the shared state as another process may have recorded it; reports are kept while it
            //is unknown too, and ours are withheld if it says "send" (globalWithholdOwn)
            break;
        case CrashReportConsent::given:
#if defined ZEN_MAC //nothing from a revoked period may be uploaded: delete first (see markRevokedPeriod())
            endRevokedPeriod(globalDatabasePath);
#endif
            sentry_user_consent_give(); //sends the kept envelopes and lets Crashpad upload its pending reports
            break;
        case CrashReportConsent::revoked:
#if defined ZEN_MAC
            markRevokedPeriod(globalDatabasePath); //before the change: a crash right after it is covered
            sentry_user_consent_revoke();
            deleteAllReports(globalDatabasePath);
#else
            sentry_user_consent_revoke();
            deleteKeptReports(globalDatabasePath);
#endif
            break;
    }
}


void zen::shutdownCrashReporting()
{
    if (!globalActive.exchange(false))
        return;
    sentry_close(); //waits up to the shutdown timeout for pending events
}


void zen::addCrashBreadcrumb(const std::string& category, const std::wstring& message)
{
    if (!globalActive)
        return;
    sentry_value_t crumb = sentry_value_new_breadcrumb("default", scrub(utfTo<std::string>(message)).c_str());
    sentry_value_set_by_key(crumb, "category", sentry_value_new_string(category.c_str()));
    sentry_add_breadcrumb(crumb);
}


void zen::reportInternalError(const std::wstring& message)
{
    if (!globalActive)
        return;
    //scrubbed again in beforeSend(), together with the rest of the event
    sentry_value_t event = sentry_value_new_message_event(SENTRY_LEVEL_ERROR, "internal", scrub(utfTo<std::string>(message)).c_str());
    sentry_capture_event(event);
}


void zen::triggerTestCrash(TestCrash kind)
{
    switch (kind)
    {
        case TestCrash::segv:
        {
            int* volatile ptr = nullptr; //volatile: the compiler can't know it's null, so it emits a real write
            *ptr = 42;
            std::raise(SIGSEGV); //unreachable unless address 0 is mapped
            break;
        }
        case TestCrash::abort:
            std::abort();
            break;

        case TestCrash::internalError:
        {
            //with what must be scrubbed, so Tests/sentry/run.sh can check it: the database path (in the user's home), a Windows
            //path, an SFTP URL with credentials, and the private words (user and host name)
            std::wstring msg = L"Test internal error (FFS_TEST_CRASH) in \"" + utfTo<std::wstring>(globalDatabasePath) +
                               L"\", C:\\Users\\john\\x.txt, sftp://john:secret@example.com/x";
            for (const std::string& word : globalPrivateWords)
                msg += L", " + utfTo<std::wstring>(word);
            reportInternalError(msg);
            break;
        }
    }
}
